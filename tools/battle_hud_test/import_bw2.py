"""Convert original BW2 cell artwork without scaling its outline.
Normal builds use the generated header; BW2 is only needed to regenerate it.
"""
from pathlib import Path
import argparse
import collections
import hashlib
import json
import shutil
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'battle_camera_test'))
from preview_backgrounds import read_png
from audit_bw2_hud import decode


def tiles(path):
    w, h, p, _ = read_png(path)
    return [p[ty+y][tx+x] for ty in range(0,h,8) for tx in range(0,w,8)
            for y in range(8) for x in range(8)]


def cell(directory, number):
    data = tiles(directory / f'{number}.png')
    record = decode(directory / f'{number+1}.ncer')
    l,t,r,b = record['bounds']
    image = [[0]*(r-l) for _ in range(b-t)]
    for e in record['entries']:
        assert not (e['attributes'][1] & 0x3000)
        for y in range(e['height']):
            for x in range(e['width']):
                image[e['y']-t+y][e['x']-l+x] = data[e['tile']*128 + ((y//8)*(e['width']//8)+x//8)*64+y%8*8+x%8]
    return image


def convert(directory):
    frames = []
    # Keep the native body outline. Clear baked labels to their row's tone;
    # the GBA draws those fields separately. Reuse its existing HUD palette.
    remap = {0:0, 2:4, 13:2, 3:2, 15:3, 1:1, 14:1, 11:9, 12:11}
    for number in (435,438):
        original = cell(directory, number)
        image = [[0]*128 for _ in range(32)]
        end = 28 if number == 435 else 32
        for sy in range(17,end):
            row = original[sy]
            tone = next(iter(collections.Counter(v for v in row if v in (13,3,15)).most_common(1)), (2,0))[0]
            for x,value in enumerate(row):
                if value in (1,14,11,12):
                    value = tone
                image[sy-4][x] = remap[value]
            assert [bool(v) for v in row] == [bool(v) for v in image[sy-4]]
        frames.append(image)
    source = tiles(directory / '434.png')
    slash = cell(directory, 456)
    glyphs = []
    for number in range(11):
        rows = [source[0x520*2+number*64+y*8:0x520*2+number*64+(y+1)*8]
                if number < 10 else slash[y][24:32] for y in range(1,7)]
        glyphs.append([[1 if v == 1 else 2 if v == 14 else 0 for v in row] for row in rows])
    return frames, glyphs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('bw2', type=Path)
    args = parser.parse_args()
    source = args.bw2 / 'res/graphics/btlv'
    dest = Path('graphics/battle_interface/bw2_original')
    dest.mkdir(exist_ok=True)
    manifest = {}
    for name in ('434.png','435.png','436.ncer','438.png','439.ncer','456.png','457.ncer'):
        shutil.copyfile(source/name, dest/name)
        manifest[name] = hashlib.sha256((source/name).read_bytes()).hexdigest()
    (dest/'provenance.json').write_text(json.dumps(manifest,indent=2)+'\n')
    frames, glyphs = convert(dest)
    text = '// Generated by tools/battle_hud_test/import_bw2.py. Native-size BW2 body outlines.\n'
    text += 'static const u8 sBw2HudFrames[2][32][64] = {\n'
    for frame in frames:
        text += '    {\n'
        for row in frame:
            text += '        {'+', '.join(f'0x{row[x]|row[x+1]<<4:02X}' for x in range(0,128,2))+'},\n'
        text += '    },\n'
    text += '};\nstatic const u8 sBw2HudDigits[11][6][8] = {\n'
    for glyph in glyphs:
        text += '    {'+', '.join('{'+', '.join(map(str,row))+'}' for row in glyph)+'},\n'
    text += '};\n'
    Path('src/data/bw2_hud_assets.h').write_text(text, newline='\n')
    print('Imported native BW2 player/opponent plate outlines and compact digit ink.')


if __name__ == '__main__':
    main()
